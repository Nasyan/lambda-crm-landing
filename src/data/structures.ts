/** Разбираем ввод посетителя. Не угадали — отдаём типовой каркас честно. */
export function resolveStructure(input: string): StructureSpec {
  const q = input.trim().toLowerCase()
  if (!q) return STRUCTURES[0]
  for (const s of STRUCTURES) {
    if (s.match.some((m) => q.includes(m))) return s
  }
  return FALLBACK
}

export const ROTATING_PROMPTS = STRUCTURES.map((s) => s.prompt)
